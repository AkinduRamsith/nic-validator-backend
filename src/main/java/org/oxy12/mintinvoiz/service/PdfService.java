package org.oxy12.mintinvoiz.service;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.oxy12.mintinvoiz.entity.InvoiceEntity;
import org.oxy12.mintinvoiz.repository.InvoiceRepository;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.time.format.DateTimeFormatter;

@Service
@RequiredArgsConstructor
@Slf4j
public class PdfService {

    private final InvoiceRepository invoiceRepository;
    private final QuotaService quotaService;

    @Value("${invoice.pdf.watermark.enabled:true}")
    private boolean watermarkEnabled;

    @Value("${invoice.pdf.watermark.text:Generated by Mint Invoiz}")
    private String watermarkText;

    public Resource generateInvoicePdf(Long userId, Long invoiceId) {
        // Check print quota
        if (!quotaService.canPrintInvoice(userId)) {
            throw new RuntimeException("Print quota exceeded. Please upgrade your plan.");
        }

        InvoiceEntity invoice = invoiceRepository.findById(invoiceId)
                .orElseThrow(() -> new RuntimeException("Invoice not found"));

        if (!invoice.getUser().getId().equals(userId)) {
            throw new RuntimeException("Access denied");
        }

        try {
            byte[] pdfBytes = generatePdfBytes(invoice);
            quotaService.incrementPrintQuota(userId);
            
            return new ByteArrayResource(pdfBytes);
        } catch (Exception e) {
            log.error("Failed to generate PDF for invoice {}: {}", invoiceId, e.getMessage());
            throw new RuntimeException("Failed to generate PDF", e);
        }
    }

    private byte[] generatePdfBytes(InvoiceEntity invoice) {
        // TODO: Implement actual PDF generation using iText
        // This is a placeholder implementation
        
        try {
            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            
            // Create a simple PDF content (placeholder)
            String pdfContent = generatePdfContent(invoice);
            baos.write(pdfContent.getBytes());
            
            log.info("PDF generated for invoice: {}", invoice.getInvoiceNumber());
            return baos.toByteArray();
            
        } catch (Exception e) {
            log.error("Error generating PDF: {}", e.getMessage());
            throw new RuntimeException("PDF generation failed", e);
        }
    }

    private String generatePdfContent(InvoiceEntity invoice) {
        // This is a placeholder - in real implementation, use iText to create proper PDF
        StringBuilder content = new StringBuilder();
        
        content.append("MINT INVOIZ INVOICE\n");
        content.append("===================\n\n");
        content.append("Invoice Number: ").append(invoice.getInvoiceNumber()).append("\n");
        content.append("Date: ").append(invoice.getInvoiceDate().format(DateTimeFormatter.ofPattern("yyyy-MM-dd"))).append("\n");
        content.append("Client: ").append(invoice.getClient().getCompanyName()).append("\n");
        content.append("Email: ").append(invoice.getClient().getEmail()).append("\n\n");
        
        content.append("ITEMS:\n");
        content.append("------\n");
        if (invoice.getInvoiceItems() != null) {
            invoice.getInvoiceItems().forEach(item -> {
                content.append(String.format("%-30s %10s x %10s = %10s\n", 
                    item.getItemName(),
                    item.getQuantity().toString(),
                    item.getUnitPrice().toString(),
                    item.getLineTotal().toString()));
            });
        }
        
        content.append("\n");
        content.append("Subtotal: $").append(invoice.getSubtotal()).append("\n");
        content.append("Tax: $").append(invoice.getTotalTax()).append("\n");
        content.append("Discount: $").append(invoice.getTotalDiscount()).append("\n");
        content.append("TOTAL: $").append(invoice.getGrandTotal()).append("\n\n");
        
        if (invoice.getNotes() != null) {
            content.append("Notes: ").append(invoice.getNotes()).append("\n");
        }
        
        if (watermarkEnabled) {
            content.append("\n").append(watermarkText).append("\n");
        }
        
        return content.toString();
    }
}